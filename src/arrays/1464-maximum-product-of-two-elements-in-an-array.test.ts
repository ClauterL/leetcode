import { maxProduct } from "./1464-maximum-product-of-two-elements-in-an-array";

describe("1464. Maximum Product of Two Elements in an Array", () => {
it("example 1", () => expect(maxProduct([3, 4, 5, 2])).toBe(12));
it("example 2", () => expect(maxProduct([1, 5, 4, 5])).toBe(16));
it("example 3", () => expect(maxProduct([3, 7])).toBe(12));
});
