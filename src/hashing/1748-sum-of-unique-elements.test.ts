import { sumOfUnique } from "./1748-sum-of-unique-elements";

describe("1748. Sum of Unique Elements", () => {
it("example 1", () => expect(sumOfUnique([1, 2, 3, 2])).toBe(4));
it("example 2", () => expect(sumOfUnique([1, 1, 1, 1, 1])).toBe(0));
it("example 3", () => expect(sumOfUnique([1, 2, 3, 4, 5])).toBe(15));
});
